import { CfnOutput, Duration, Stack, Validations, type StackProps } from 'aws-cdk-lib';
import type * as ecr from 'aws-cdk-lib/aws-ecr';
import * as iam from 'aws-cdk-lib/aws-iam';
import { type Construct } from 'constructs';

import { type VlpConfig } from './config';

export interface CiCdStackProps extends StackProps {
  config: VlpConfig;
  apiRepo: ecr.IRepository;
  workerRepo: ecr.IRepository;
}

const GITHUB_OIDC_HOST = 'token.actions.githubusercontent.com';

/**
 * Role assumed by GitHub Actions via OIDC (no long-lived AWS keys in GitHub).
 *
 * Trust: only this repository, and only from the `main` branch or the `production` environment.
 * Permissions: push images to our ECR repos, assume the CDK bootstrap roles (which do the actual
 * CloudFormation work), sync the web bucket and invalidate CloudFront.
 *
 * This stack is deployed manually by an admin and deliberately NOT by the pipeline,
 * so CI can never widen its own permissions.
 */
export class CiCdStack extends Stack {
  constructor(scope: Construct, id: string, props: CiCdStackProps) {
    super(scope, id, props);
    const { config } = props;
    const { githubRepo } = config;
    const [owner, repo] = githubRepo.split('/');
    // Matches GitHub's immutable-ID subject format, e.g.
    // repo:rkumwt@21355037/video-lms@1467775537:ref:refs/heads/main
    const subject = `repo:${owner}@${config.githubOwnerId}/${repo}@${config.githubRepoId}`;

    // There can be only one GitHub OIDC provider per account: import it if it already exists.
    const provider = config.githubOidcProviderExists
      ? iam.OpenIdConnectProvider.fromOpenIdConnectProviderArn(
          this,
          'GitHubOidc',
          `arn:${this.partition}:iam::${this.account}:oidc-provider/${GITHUB_OIDC_HOST}`,
        )
      : new iam.OpenIdConnectProvider(this, 'GitHubOidc', {
          url: `https://${GITHUB_OIDC_HOST}`,
          clientIds: ['sts.amazonaws.com'],
        });

    const role = new iam.Role(this, 'GitHubDeployRole', {
      roleName: `${config.appName}-github-deploy`,
      description: `GitHub Actions deploy role for ${githubRepo}`,
      maxSessionDuration: Duration.hours(1),
      assumedBy: new iam.WebIdentityPrincipal(provider.openIdConnectProviderArn, {
        StringEquals: { [`${GITHUB_OIDC_HOST}:aud`]: 'sts.amazonaws.com' },
        StringLike: {
          [`${GITHUB_OIDC_HOST}:sub`]: [
            `${subject}:ref:refs/heads/main`,
            `${subject}:environment:production`,
          ],
        },
      }),
    });

    // 1) CDK deploys: assume the bootstrap roles (deploy, file/image publishing, lookup).
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'AssumeCdkBootstrapRoles',
        actions: ['sts:AssumeRole'],
        resources: [`arn:${this.partition}:iam::${this.account}:role/cdk-hnb659fds-*`],
      }),
    );

    // 2) Push images.
    props.apiRepo.grantPullPush(role);
    props.workerRepo.grantPullPush(role);

    // 3) Read stack outputs (bucket name, distribution id, URL).
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'ReadStackOutputs',
        actions: ['cloudformation:DescribeStacks'],
        resources: [
          `arn:${this.partition}:cloudformation:${this.region}:${this.account}:stack/Vlp-*/*`,
        ],
      }),
    );

    // 4) Upload the SPA. The bucket name is generated by the App stack, hence the prefix.
    const webBucketArn = `arn:${this.partition}:s3:::vlp-app-webbucket*`;
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'SyncWebBucket',
        actions: ['s3:ListBucket', 's3:GetObject', 's3:PutObject', 's3:DeleteObject'],
        resources: [webBucketArn, `${webBucketArn}/*`],
      }),
    );

    // 5) Invalidate CloudFront after uploading index.html.
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'InvalidateCloudFront',
        actions: ['cloudfront:CreateInvalidation', 'cloudfront:GetInvalidation'],
        resources: [`arn:${this.partition}:cloudfront::${this.account}:distribution/*`],
      }),
    );

    // 6) Read-only ECS status for post-deploy checks.
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: 'DescribeEcs',
        actions: ['ecs:DescribeServices', 'ecs:DescribeTasks', 'ecs:ListTasks'],
        resources: ['*'],
      }),
    );

    new CfnOutput(this, 'DeployRoleArn', { value: role.roleArn });

    Validations.of(this).acknowledge({
      id: 'AwsSolutions-IAM5',
      reason:
        'Wildcards are scoped by prefix: CDK bootstrap roles (cdk-hnb659fds-*), Vlp-* stacks, ' +
        'the generated web bucket name, CloudFront distributions in this account, and ' +
        'ecr:GetAuthorizationToken / ECS Describe* which do not support resource-level permissions.',
    });
  }
}
